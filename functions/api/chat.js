function corsHeaders() {
  return {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
  };
}

function isOwnerQuestion(text) {
  const t = text.toLowerCase();
  return [
    "مالك", "المالك", "مؤسس", "المؤسس", "صاحب", "ceo", "founder", "owner",
    "who owns", "who founded", "who's the owner", "who is the owner",
    "مين صاحب", "من صاحب", "مين مؤسس", "من مؤسس",
  ].some((k) => t.includes(k.toLowerCase()));
}

const OWNER_FAIL_CLOSED =
  "للتفاصيل عن الفريق، عبّوا نموذج التواصل في الموقع وبيتواصل معكم فريق بوستر AI.";

function scrubReply(reply) {
  let r = String(reply || "").trim().slice(0, 520);
  r = r.replace(/\[\s*clip\s*:[^\]]*\]/gi, "").replace(/\bclip\s*[\w_-]*/gi, "").trim();
  // Prefer Arabic for voice
  const ar = (r.match(/[\u0600-\u06FF]/g) || []).length;
  const en = (r.match(/[A-Za-z]/g) || []).length;
  if (!r || (en > 8 && en >= ar)) {
    return "ممكن ما التقطت مقصدك كامل. هل تبحث عن حل لمشكلة أو عملية معينة في شركتكم، أو تبغى تعرف عن خدمات بوستر AI بشكل عام؟";
  }
  return r;
}

export async function onRequestOptions() {
  return new Response(null, { status: 204, headers: corsHeaders() });
}

export async function onRequestPost(context) {
  const headers = { "Content-Type": "application/json", ...corsHeaders() };

  try {
    let body;
    try {
      body = await context.request.json();
    } catch {
      return Response.json({ error: "Invalid JSON" }, { status: 400, headers });
    }

    const message = (body.message || body.text || "").toString().trim().slice(0, 500);
    if (!message) {
      return Response.json({ error: "message required" }, { status: 400, headers });
    }

    if (isOwnerQuestion(message)) {
      return Response.json({ reply: OWNER_FAIL_CLOSED, model: "pack-people" }, { headers });
    }

    if (!context.env.AI) {
      return Response.json(
        { error: "Workers AI binding missing (name must be AI)." },
        { status: 503, headers }
      );
    }

    // Keep more turns for multi-intent / follow-ups like "طيب كم؟"
    const history = Array.isArray(body.history) ? body.history.slice(-10) : [];
    const messages = [
      { role: "system", content: SYSTEM_PROMPT },
      ...history
        .filter((m) => m && (m.role === "user" || m.role === "assistant") && m.content)
        .map((m) => ({
          role: m.role,
          content: String(m.content).slice(0, 700),
        })),
      { role: "user", content: message },
    ];

    const result = await context.env.AI.run("@cf/meta/llama-3.2-3b-instruct", {
      messages,
      max_tokens: 220,
      temperature: 0.35,
    });

    let reply =
      (typeof result === "string" && result) ||
      result?.response ||
      result?.result?.response ||
      "";
    reply = scrubReply(reply);

    return Response.json(
      { reply, model: "workers-ai-llama-3.2-3b" },
      { headers }
    );
  } catch (err) {
    return Response.json(
      {
        error: "Talk brain failed",
        detail: String(err && err.message ? err.message : err).slice(0, 300),
      },
      { status: 502, headers }
    );
  }
}
